// Regenerates lib/data/countries.dart from the World Bank API.
//
//   dart run tool/update_life_expectancy.dart
//
// Source: World Bank, World Development Indicators (free, no key):
//   SP.DYN.LE00.FE.IN  Life expectancy at birth, female (years)
//   SP.DYN.LE00.MA.IN  Life expectancy at birth, male (years)
// The World Bank takes these figures from the UN Population Division's
// World Population Prospects. Data licence: CC BY 4.0.
import 'dart:convert';
import 'dart:io';

import 'package:http/http.dart' as http;

const _api = 'https://api.worldbank.org/v2';
const _female = 'SP.DYN.LE00.FE.IN';
const _male = 'SP.DYN.LE00.MA.IN';

/// Friendlier names for how people search, where the World Bank's official
/// short names read awkwardly ("Korea, Rep.").
const _names = {
  'BS': 'Bahamas',
  'CD': 'Congo (DR)',
  'CG': 'Congo',
  'CI': 'Côte d’Ivoire',
  'CW': 'Curaçao',
  'EG': 'Egypt',
  'FM': 'Micronesia',
  'GM': 'Gambia',
  'HK': 'Hong Kong',
  'IR': 'Iran',
  'KG': 'Kyrgyzstan',
  'KN': 'Saint Kitts and Nevis',
  'KP': 'North Korea',
  'KR': 'South Korea',
  'LA': 'Laos',
  'LC': 'Saint Lucia',
  'MF': 'Saint Martin',
  'MO': 'Macao',
  'PS': 'Palestine',
  'RU': 'Russia',
  'SK': 'Slovakia',
  'ST': 'São Tomé and Príncipe',
  'SX': 'Sint Maarten',
  'SY': 'Syria',
  'TR': 'Türkiye',
  'VC': 'Saint Vincent and the Grenadines',
  'VE': 'Venezuela',
  'VI': 'U.S. Virgin Islands',
  'VN': 'Vietnam',
  'YE': 'Yemen',
};

Future<List<dynamic>> _get(String path) async {
  final res = await http.get(Uri.parse('$_api/$path'));
  if (res.statusCode != 200) {
    throw HttpException('${res.statusCode} for $path');
  }
  final body = jsonDecode(res.body) as List<dynamic>;
  if (body.length < 2 || body[1] == null) {
    throw StateError('No data for $path: ${res.body}');
  }
  return body[1] as List<dynamic>;
}

/// Most recent non-empty value per ISO2 code, with its year.
Future<Map<String, (double, String)>> _indicator(String id) async {
  final rows = await _get(
    'country/all/indicator/$id?format=json&mrnev=1&per_page=400',
  );
  return {
    for (final r in rows)
      if (r['value'] != null)
        (r['country']['id'] as String): (
          (r['value'] as num).toDouble(),
          r['date'] as String,
        ),
  };
}

String _q(String s) => "'${s.replaceAll(r'\', r'\\').replaceAll("'", r"\'")}'";

Future<void> main() async {
  final economies = (await _get('country?format=json&per_page=400'))
      .where((c) => c['region']['value'] != 'Aggregates')
      .map((c) => (c['iso2Code'] as String, (c['name'] as String).trim()))
      .toList();
  final female = await _indicator(_female);
  final male = await _indicator(_male);

  final world = (female['1W'], male['1W']);
  if (world.$1 == null || world.$2 == null) throw StateError('No world data');

  final rows = <(String, String, double, double)>[];
  final years = <String>{};
  for (final (code, name) in economies) {
    final f = female[code], m = male[code];
    if (f == null || m == null) continue;
    rows.add((code, _names[code] ?? name, f.$1, m.$1));
    years
      ..add(f.$2)
      ..add(m.$2);
  }
  rows.sort((a, b) => a.$2.toLowerCase().compareTo(b.$2.toLowerCase()));
  final sorted = years.toList()..sort();
  final yearLabel = sorted.length == 1
      ? sorted.single
      : '${sorted.first}–${sorted.last}';

  String r1(double v) => v.toStringAsFixed(1);
  final out = StringBuffer()
    ..writeln(
      '// GENERATED by tool/update_life_expectancy.dart. Do not edit by hand.',
    )
    ..writeln('//')
    ..writeln('// Source: World Bank, World Development Indicators ($_female,')
    ..writeln('// $_male), from the UN Population Division, World Population')
    ..writeln('// Prospects. Licence: CC BY 4.0. Year: $yearLabel.')
    ..writeln()
    ..writeln('/// Period life expectancy at birth, by sex.')
    ..writeln('class CountryLifeExpectancy {')
    ..writeln(
      '  const CountryLifeExpectancy(this.code, this.name, this.female, this.male);',
    )
    ..writeln()
    ..writeln(
      '  /// ISO 3166-1 alpha-2 code. `XX` is the world-average fallback.',
    )
    ..writeln('  final String code;')
    ..writeln('  final String name;')
    ..writeln('  final double female;')
    ..writeln('  final double male;')
    ..writeln()
    ..writeln('  double get average => (female + male) / 2;')
    ..writeln('}')
    ..writeln()
    ..writeln(
      '/// Where the figures come from, for the "How we estimate" screen.',
    )
    ..writeln("const lifeExpectancySource =")
    ..writeln(
      "    'World Bank WDI, from UN World Population Prospects ($yearLabel)';",
    )
    ..writeln()
    ..writeln("const worldCode = 'XX';")
    ..writeln()
    ..writeln('/// The world average, for anyone whose country isn\'t listed.')
    ..writeln('const worldAverage = CountryLifeExpectancy(')
    ..writeln("  worldCode,")
    ..writeln("  'Somewhere else',")
    ..writeln('  ${r1(world.$1!.$1)},')
    ..writeln('  ${r1(world.$2!.$1)},')
    ..writeln(');')
    ..writeln()
    ..writeln('const countries = <CountryLifeExpectancy>[');
  for (final (code, name, f, m) in rows) {
    out.writeln(
      "  CountryLifeExpectancy('$code', ${_q(name)}, ${r1(f)}, ${r1(m)}),",
    );
  }
  out
    ..writeln('  worldAverage,')
    ..writeln('];')
    ..writeln()
    ..writeln('CountryLifeExpectancy countryByCode(String? code) =>')
    ..writeln(
      '    countries.firstWhere((c) => c.code == code, orElse: () => worldAverage);',
    )
    ..writeln()
    ..writeln(
      '/// Looks a country up by name, including names saved by v1 of the app.',
    )
    ..writeln('CountryLifeExpectancy? countryByName(String name) {')
    ..writeln('  final n = name.toLowerCase();')
    ..writeln('  for (final c in countries) {')
    ..writeln('    if (c.name.toLowerCase() == n) return c;')
    ..writeln('  }')
    ..writeln('  return null;')
    ..writeln('}');

  File('lib/data/countries.dart').writeAsStringSync(out.toString());
  stdout.writeln(
    'Wrote ${rows.length} countries ($yearLabel). '
    'World: ${r1(world.$1!.$1)} F / ${r1(world.$2!.$1)} M.',
  );
}
